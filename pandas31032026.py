#Función para recortar arreglos numpy bidimensionales. (CLAUDE)
#Parámetros: Arreglo numpy bidimensional, rango de filas a borrar, rango de columnas a borrar.
#Salida: Retorna el mismo arreglo recortado.
def cut_array(arr, row_range, col_range):
    return arr[row_range[0]:row_range[1], col_range[0]:col_range[1]]

#Función para recortar arreglos numpy tridimensionales. (CLAUDE)
#Parámetros: Arreglo numpy tridimensional, rango de filas a borrar, rango de columnas a borrar.
#Salida: Retorna un nuevo arreglo tridimensional recortado.
def cut_hyperspectral_cube(cube, row_range, col_range, band_range=None):
    if band_range is None:
        return np.array([cut_array(band, row_range, col_range) for band in cube])
    else:
        return np.array([cut_array(band, row_range, col_range) for band in cube[band_range[0]:band_range[1]]])

