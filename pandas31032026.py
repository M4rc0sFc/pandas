# 1. FUNCIÓN DE FRECUENCIAS (la misma que ya usas para SAVI)
# ─────────────────────────────────────────────────────────────────────────────
def calculate_frequencies(matrix):
    """
    Calcula frecuencias de valores en 10 bins equidistantes de -1 a 1.
    Funciona para NDVI, SAVI o cualquier índice acotado en [-1, 1].
    """
    bins = np.linspace(-1, 1, 11)
    flat_matrix = matrix.flatten()
    frequencies, _ = np.histogram(flat_matrix, bins=bins)
    return frequencies


