def calculate_ndvi_statistics(ndvi_matrix):
    """
    Calcula estadísticas descriptivas para una matriz NDVI.

    El NDVI (Normalized Difference Vegetation Index) produce valores en el
    rango [-1, 1], donde:
      - Valores negativos: agua, nieve, nubes
      - Cercanos a 0: suelo desnudo, roca, áreas urbanas
      - Valores positivos crecientes: vegetación cada vez más densa y saludable

    Parameters
    ----------
    ndvi_matrix : numpy.ndarray
        Matriz 2D con valores NDVI (rango teórico: -1 a 1).

    Returns
    -------
    dict
        Diccionario con las siguientes estadísticas:
        - mean      : media aritmética de todos los píxeles
        - variance  : varianza muestral (ddof=1)
        - std_dev   : desviación estándar muestral (ddof=1)
        - min       : valor mínimo
        - max       : valor máximo
        - median    : mediana
        - range     : diferencia entre máximo y mínimo
        - cv        : coeficiente de variación (%), solo fiable si mean ≠ 0
        - count     : número total de píxeles válidos (sin NaN)
    """
    ndvi_flat = ndvi_matrix.flatten()
    ndvi_clean = ndvi_flat[~np.isnan(ndvi_flat)]

    mean_val = np.mean(ndvi_clean)

    stats = {
        'mean':     mean_val,
        'variance': np.var(ndvi_clean, ddof=1),
        'std_dev':  np.std(ndvi_clean, ddof=1),
        'min':      np.min(ndvi_clean),
        'max':      np.max(ndvi_clean),
        'median':   np.median(ndvi_clean),
        'range':    np.max(ndvi_clean) - np.min(ndvi_clean),
        'cv':       (np.std(ndvi_clean, ddof=1) / mean_val * 100)
                     if mean_val != 0 else np.inf,
        'count':    len(ndvi_clean),
    }

    return stats


def interpret_ndvi_variability(stats):
    """
    Proporciona una interpretación ecológica de la variabilidad NDVI.

    Umbrales estándar de la literatura para NDVI (rango -1 a 1):
        NDVI < 0.0   → Agua, nieve o superficies no vegetadas
        0.0 – 0.2    → Suelo desnudo, roca o vegetación extremadamente escasa
        0.2 – 0.4    → Vegetación dispersa o en estrés hídrico
        0.4 – 0.6    → Vegetación moderada / cultivos en desarrollo
        > 0.6        → Vegetación densa y saludable

    Criterios de variabilidad espacial (CV):
        CV < 20 %    → Variabilidad BAJA  (cobertura homogénea)
        20–50 %      → Variabilidad MODERADA (mosaico de coberturas)
        CV > 50 %    → Variabilidad ALTA  (alta heterogeneidad)

    Parameters
    ----------
    stats : dict
        Diccionario generado por ``calculate_ndvi_statistics``.
    """
    cv        = stats['cv']
    std_dev   = stats['std_dev']
    mean_ndvi = stats['mean']

    print("=== INTERPRETACIÓN ECOLÓGICA DE VARIABILIDAD NDVI ===")
    print(f"NDVI promedio:            {mean_ndvi:.3f}")
    print(f"Desviación estándar:      {std_dev:.3f}")
    print(f"Coeficiente de variación: {cv:.1f}%")
    print(f"Rango:                    {stats['range']:.3f}")
    print()

    # Interpretación del NDVI promedio
    if mean_ndvi < 0.0:
        veg_condition = "Agua, nieve o superficies no vegetadas"
    elif mean_ndvi < 0.2:
        veg_condition = "Suelo desnudo o vegetación extremadamente escasa"
    elif mean_ndvi < 0.4:
        veg_condition = "Vegetación dispersa o en estrés hídrico"
    elif mean_ndvi < 0.6:
        veg_condition = "Vegetación moderada / cultivos en desarrollo"
    else:
        veg_condition = "Vegetación densa y saludable"

    print(f"Condición general de vegetación: {veg_condition}")
    print()

    # Interpretación de la variabilidad espacial
    if cv < 20:
        variability = "BAJA"
        interpretation = """
        - Condiciones de vegetación relativamente homogéneas
        - Manejo uniforme o condiciones ambientales similares
        - Posible monocultivo o ecosistema poco diverso
        - Condiciones de suelo y agua relativamente uniformes
        """
    elif cv < 50:
        variability = "MODERADA"
        interpretation = """
        - Heterogeneidad espacial moderada en vegetación
        - Diversidad de usos del suelo o condiciones ambientales
        - Posible mosaico de diferentes tipos de cobertura
        - Variaciones naturales en topografía o microclimas
        """
    else:
        variability = "ALTA"
        interpretation = """
        - Alta heterogeneidad espacial en vegetación
        - Gran diversidad de usos del suelo y condiciones
        - Posibles gradientes ambientales fuertes
        - Áreas con alta diversidad de hábitats
        - Posible presencia de disturbios o estrés heterogéneo
        """

    print(f"Variabilidad espacial: {variability} (CV = {cv:.1f}%)")
    print(f"Implicaciones ecológicas:{interpretation}")


