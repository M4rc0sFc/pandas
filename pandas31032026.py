# PASO 3: FUNCIÓN PRINCIPAL — CALCULAR RESOLUCIÓN POR REGIÓN
# =============================================================================

def calcular_resolucion_por_region(wl_nm, fwhm=None, regiones=REGIONES_RESOLUCION):
    """
    Para un array de longitudes de onda (y opcionalmente FWHM),
    calcula estadísticas de resolución espectral por región.

    Parámetros:
    -----------
    wl_nm : np.array
        Array 1D con los centros de longitud de onda de cada banda (en nm).
    fwhm : np.array o None
        Array 1D con los FWHM de cada banda (en nm). Si es None, se usa Δλ.
    regiones : dict
        Diccionario {nombre_region: (λ_min, λ_max)}.

    Retorna:
    --------
    df_stats : pd.DataFrame
        Tabla con estadísticas de resolución por región.
    delta_lambda : np.array
        Array con las diferencias Δλ entre bandas consecutivas.
    """
    # --- Calcular Δλ entre bandas consecutivas ---
    # Δλ_i = λ_{i+1} - λ_i
    # Este array tiene (N-1) elementos para N bandas
    delta_lambda = np.diff(wl_nm)

    # Para asignar cada Δλ a una región, usamos el punto medio entre
    # las dos bandas que definen cada diferencia:
    # punto_medio_i = (λ_i + λ_{i+1}) / 2
    puntos_medios = (wl_nm[:-1] + wl_nm[1:]) / 2.0

    filas = []
    for nombre_region, (lam_min, lam_max) in regiones.items():
        # Filtrar los Δλ cuyos puntos medios caen dentro de esta región
        mascara = (puntos_medios >= lam_min) & (puntos_medios < lam_max)
        dl_region = delta_lambda[mascara]

        if len(dl_region) == 0:
            filas.append({
                'Región': nombre_region,
                'λ_min (nm)': lam_min,
                'λ_max (nm)': lam_max,
                'N bandas': 0,
                'Δλ media (nm)': np.nan,
                'Δλ mediana (nm)': np.nan,
                'Δλ SD (nm)': np.nan,
                'Δλ mín (nm)': np.nan,
                'Δλ máx (nm)': np.nan,
                'CV (%)': np.nan,
            })
            continue

        # Estadísticas del espaciado Δλ en esta región
        fila = {
            'Región': nombre_region,
            'λ_min (nm)': lam_min,
            'λ_max (nm)': lam_max,
            'N bandas': int(mascara.sum()),
            'Δλ media (nm)': np.mean(dl_region),
            'Δλ mediana (nm)': np.median(dl_region),
            'Δλ SD (nm)': np.std(dl_region, ddof=1) if len(dl_region) > 1 else 0.0,
            'Δλ mín (nm)': np.min(dl_region),
            'Δλ máx (nm)': np.max(dl_region),
            'CV (%)': (np.std(dl_region, ddof=1) / np.mean(dl_region) * 100)
                      if (len(dl_region) > 1 and np.mean(dl_region) != 0) else 0.0,
        }

        # Si tenemos FWHM, añadir estadísticas de FWHM para esta región
        if fwhm is not None:
            # Para FWHM, las bandas (no los puntos medios) definen la región
            mascara_fwhm = (wl_nm >= lam_min) & (wl_nm < lam_max)
            fwhm_region = fwhm[mascara_fwhm]
            if len(fwhm_region) > 0:
                fila['FWHM media (nm)'] = np.mean(fwhm_region)
                fila['FWHM SD (nm)'] = np.std(fwhm_region, ddof=1) if len(fwhm_region) > 1 else 0.0
            else:
                fila['FWHM media (nm)'] = np.nan
                fila['FWHM SD (nm)'] = np.nan

        filas.append(fila)

    # Añadir fila GLOBAL (todo el espectro)
    fila_global = {
        'Región': '*** GLOBAL ***',
        'λ_min (nm)': wl_nm.min(),
        'λ_max (nm)': wl_nm.max(),
        'N bandas': len(delta_lambda),
        'Δλ media (nm)': np.mean(delta_lambda),
        'Δλ mediana (nm)': np.median(delta_lambda),
        'Δλ SD (nm)': np.std(delta_lambda, ddof=1),
        'Δλ mín (nm)': np.min(delta_lambda),
        'Δλ máx (nm)': np.max(delta_lambda),
        'CV (%)': np.std(delta_lambda, ddof=1) / np.mean(delta_lambda) * 100,
    }
    if fwhm is not None:
        fila_global['FWHM media (nm)'] = np.mean(fwhm)
        fila_global['FWHM SD (nm)'] = np.std(fwhm, ddof=1)

    filas.append(fila_global)

    df_stats = pd.DataFrame(filas)
    return df_stats, delta_lambda, puntos_medios


