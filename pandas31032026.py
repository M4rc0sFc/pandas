    stats = calculate_savi_statistics(savi_matrix)

    print("=== ESTADÍSTICAS DESCRIPTIVAS SAVI ===")
    for key, value in stats.items():
        if key != 'count':
            print(f"  {key.capitalize():12s}: {value:.4f}")
        else:
            print(f"  {key.capitalize():12s}: {value}")
    print()

    # --- 3. Interpretación ecológica ---
    interpret_savi_variability(stats)

    # Separador visual entre cubos
    print("\n" + "—" * 60 + "\n")

    return stats, freqs


