"""# Se calcula la frecuencia de los valores SAVI de cada parcela."""

def calculate_frequencies(matrix):
    # Define the bin edges for the intervals
    bins = np.linspace(-1, 1, 11)  # Creates array: [-1, -0.8, -0.6, ..., 0.8, 1]

    # Flatten the 2D array into 1D for histogram calculation
    flat_matrix = matrix.flatten()

    # Calculate frequencies using numpy's histogram function
    # We use bins[1:-1] to exclude -1 and 1 as they are edge cases
    frequencies, _ = np.histogram(flat_matrix, bins=bins)

    return frequencies

