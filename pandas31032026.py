def interpret_ndvi_frequencies(frequencies, nombre_cubo=""):
    """
    Interpreta las frecuencias de cada bin NDVI en contexto ecológico.

    Parameters:
    -----------
    frequencies : array-like
        Array de 10 frecuencias correspondientes a los bins:
        (-1,-0.8), (-0.8,-0.6), ..., (0.6,0.8), (0.8,1.0)
    nombre_cubo : str
        Nombre identificador de la parcela/cubo
    """
    total = np.sum(frequencies)

    # Etiquetas ecológicas para cada bin NDVI
    bin_labels = [
        ("(-1.0, -0.8)", "Agua profunda / artefactos del sensor"),
        ("(-0.8, -0.6)", "Agua / sombras profundas"),
        ("(-0.6, -0.4)", "Agua / superficies no vegetadas oscuras"),
        ("(-0.4, -0.2)", "Suelo húmedo / sombras densas"),
        ("(-0.2,  0.0)", "Suelo desnudo / roca / infraestructura"),
        ("( 0.0,  0.2)", "Suelo con vegetación incipiente / residuos"),
        ("( 0.2,  0.4)", "Vegetación dispersa / pastizal seco / estrés"),
        ("( 0.4,  0.6)", "Vegetación moderada / dosel parcial"),
        ("( 0.6,  0.8)", "Vegetación densa / dosel cerrado saludable"),
        ("( 0.8,  1.0)", "Vegetación muy densa / dosel completamente cerrado"),
    ]

    print(f"{'='*70}")
    print(f"  FRECUENCIAS NDVI — {nombre_cubo}")
    print(f"{'='*70}")
    print(f"  {'Bin NDVI':<18} {'Frecuencia':>12} {'%':>8}   Interpretación ecológica")
    print(f"  {'─'*66}")

    for i, (freq) in enumerate(frequencies):
        bin_range, eco_label = bin_labels[i]
        pct = (freq / total * 100) if total > 0 else 0
        bar = "█" * int(pct / 2)  # Mini barra visual
        print(f"  {bin_range:<18} {freq:>12,} {pct:>7.2f}%  {bar} {eco_label}")

    print(f"  {'─'*66}")
    print(f"  {'TOTAL':<18} {total:>12,}")
    print()

    # --- Resumen de composición de la parcela ---
    neg_pixels = np.sum(frequencies[:5])       # bins < 0
    bare_pixels = frequencies[5]                # bin 0.0-0.2
    sparse_pixels = frequencies[6]              # bin 0.2-0.4
