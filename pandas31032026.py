import re, numpy as np, pandas as pd
from pathlib import Path

# --- 1) Parser mínimo de .hdr (ENVI) ---
def read_envi_header(hdr_path):
    txt = Path(hdr_path).read_text(encoding='latin-1', errors='ignore')
    d = {}

    # key = value (línea simple)
    for m in re.finditer(r'(?mi)^\s*([\w\s]+?)\s*=\s*([^\{\n\r]+?)\s*$', txt):
        k = m.group(1).strip().lower()
        v = m.group(2).strip()
        d[k] = v

    # listas entre llaves (multi-línea), p.ej. wavelength = { ... }
    def get_list(key):
        m = re.search(rf'(?is)\b{re.escape(key)}\s*=\s*\{{(.*?)\}}', txt)
        if not m:
            return None
        raw = m.group(1)
        # separar por comas o espacios
        parts = re.split(r'[,\s]+', raw.strip())
        parts = [p for p in parts if p and p.lower()!='nan']
        return parts

    # wavelength
    wl_list = get_list('wavelength')
    if wl_list:
        try:
            wl = np.array([float(x.replace(',', '.')) for x in wl_list], dtype=float)
        except ValueError:
            # a veces vienen como "0.400000E+03"
            wl = np.array([float(x.replace(',', '.')) for x in wl_list if re.search(r'[\d\.\-eE]+', x)], dtype=float)
        d['wavelength'] = wl
    # fwhm (opcional)
    fwhm_list = get_list('fwhm')
    if fwhm_list:
        try:
            d['fwhm'] = np.array([float(x.replace(',', '.')) for x in fwhm_list], dtype=float)
        except:
            pass

    return d

def to_nanometers(wl, units):
    if units is None:
        # Inferir: si máximos ~2.5 => µm; si 400-2500 => nm.
        mx = np.nanmax(wl)
        return wl*1000.0 if mx < 50 else wl
    u = units.strip().lower()
    if 'microm' in u or u in ('µm','um'):
        return wl * 1000.0
    if 'nanom' in u or u in ('nm',):
        return wl
    # por si acaso
    mx = np.nanmax(wl)
    return wl*1000.0 if mx < 50 else wl

# --- 2) Regiones espectrales "canónicas" ---
REGIONES_NM = {
    "Blue":   (440, 480),
    "Green":  (520, 560),
    "Red":    (650, 680),
    "RE":     (705, 740),
    "NIR":    (760, 900),
    "SWIR1":  (1200, 1300),
    "SWIR2":  (1550, 1750),
    "SWIR3":  (2000, 2300),
}
ANCLAS_NM = [670, 705, 730, 780, 860, 1240]  # útiles para NDVI/NDRE/pendientes/NDWI

def nearest_band(wl_nm, target_nm):
    idx = int(np.abs(wl_nm - target_nm).argmin())
    return idx, float(wl_nm[idx])

def indices_por_region(wl_nm, regiones=REGIONES_NM):
    out = {}
    for nombre, (a,b) in regiones.items():
        idx = np.where((wl_nm >= a) & (wl_nm <= b))[0]
        out[nombre] = idx
    return out

# --- 3) Función principal por cubo: de .hdr -> índices por región ---
def mapear_regiones_y_anclas(hdr_path, bands_slice=None):
    meta = read_envi_header(hdr_path)
    wl = meta.get('wavelength', None)
    if wl is None:
        raise ValueError(f"No encontré 'wavelength' en {hdr_path}. Revisa el .hdr.")

    units = meta.get('wavelength units', None)
    wl_nm = to_nanometers(wl, units)

    # Si recortaste bandas (p.ej. 0:400), alinea wl_nm a ese recorte
    if bands_slice is not None:
        b0, b1 = bands_slice
        wl_nm = wl_nm[b0:b1]

    # Chequeos rápidos
    wl_nm = np.array(wl_nm, dtype=float)
    if not np.all(np.diff(wl_nm) >= 0):
        # En la práctica casi siempre está ordenado ascendentemente; si no, ordenamos
        order = np.argsort(wl_nm)
        wl_nm = wl_nm[order]

    # indices por región
    reg_idx = indices_por_region(wl_nm)

    # anclas cercanas
    anclas = {str(a): nearest_band(wl_nm, a) for a in ANCLAS_NM}

    # resumen
    d_wl = np.diff(wl_nm)
    resol_med = float(np.nanmedian(d_wl)) if d_wl.size else np.nan
    resumen = {
        "wl_min_nm": float(wl_nm.min()),
        "wl_max_nm": float(wl_nm.max()),
        "n_bandas": int(wl_nm.size),
        "resol_nm_mediana": resol_med,
        **{f"n_{k}": int(v.size) for k,v in reg_idx.items()}
    }

    return wl_nm, reg_idx, anclas, resumen

