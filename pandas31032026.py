def check_input(red, nir):
    """Verifica que las entradas sean arrays numpy y tengan la misma forma."""
    if not isinstance(red, np.ndarray) or not isinstance(nir, np.ndarray):
        raise TypeError("Las entradas deben ser arrays numpy.")
    if red.shape != nir.shape:
        raise ValueError("Los arrays de entrada deben tener la misma forma.")

def ndvi(red, nir):
    """Calcula el Índice de Vegetación de Diferencia Normalizada (NDVI)."""
    check_input(red, nir)
    return (nir - red) / (nir + red + 1e-8)

