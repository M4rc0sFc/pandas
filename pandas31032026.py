"""# Se calcula el índice de Vegetación NDVI mediante una función.
## El indice NDVI mide, entre otras cosas, la cantidad de agua en la vegetación de las parcelas.
"""

#Funcion que calcula el indice de vegetacion NDVI

def calculate_ndvi(nir_band, red_band):
    """
    Calculate NDVI from NIR and Red bands.

    Parameters:
    nir_band (numpy.ndarray): 2D array of Near-Infrared band digital numbers
    red_band (numpy.ndarray): 2D array of Red band digital numbers

    Returns:
    numpy.ndarray: 2D array of NDVI values
    """
    # Convert digital numbers to float to avoid integer division
    nir = nir_band.astype(float)
    red = red_band.astype(float)

    # Avoid division by zero
    denominator = nir + red
    ndvi = np.where(
        denominator != 0,
        (nir - red) / denominator,
        0  # or np.nan if you prefer to mark these as missing data
    )

    return ndvi

