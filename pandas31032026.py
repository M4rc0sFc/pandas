# 2. FUNCIÓN DE ESTADÍSTICAS DESCRIPTIVAS PARA NDVI
# ─────────────────────────────────────────────────────────────────────────────
def calculate_ndvi_statistics(ndvi_matrix):
    """
    Calcula estadísticas descriptivas para una matriz NDVI.
    Análoga a calculate_savi_statistics pero con umbrales NDVI.

    Parameters:
    -----------
    ndvi_matrix : numpy.ndarray
        Matriz 2D con valores NDVI

    Returns:
    --------
    dict : diccionario con estadísticas descriptivas
    """
    ndvi_flat = ndvi_matrix.flatten()
    ndvi_clean = ndvi_flat[~np.isnan(ndvi_flat)]

    stats = {
        'mean':     np.mean(ndvi_clean),
        'variance': np.var(ndvi_clean, ddof=1),
        'std_dev':  np.std(ndvi_clean, ddof=1),
        'min':      np.min(ndvi_clean),
        'max':      np.max(ndvi_clean),
        'median':   np.median(ndvi_clean),
        'range':    np.max(ndvi_clean) - np.min(ndvi_clean),
        'cv':       np.std(ndvi_clean, ddof=1) / np.mean(ndvi_clean) * 100,
        'count':    len(ndvi_clean)
    }
    return stats


